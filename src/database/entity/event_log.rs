use sea_orm::entity::prelude::*;

/// Records a user's successful operations.
///
/// Keyed by a surrogate `id` rather than the composite
/// `(created_at, connection_id, detail)` it used to be. That key was described as
/// giving incidental dedup, but an append-only audit trail has nothing to dedup:
/// two identical events in the same millisecond on the same connection are two
/// things that happened, and the composite key rejected the second with
/// `UNIQUE constraint failed`. `insert_log`'s error is logged and swallowed on the
/// connection path, so the effect was a silently dropped audit record — the one
/// kind of loss this table exists to prevent.
///
/// `i64`, not `i32`: the table is append-only and `list_logs` never prunes, so the
/// key has to outlast 2.1 billion rows. SQLite spells every integer width
/// `integer` so this is still a rowid alias, and `AUTOINCREMENT` there means ids
/// are never reused after a delete — the audit trail should not recycle
/// identifiers. Postgres gets `GENERATED BY DEFAULT AS IDENTITY`, MySQL
/// `AUTO_INCREMENT`.
///
/// The index on `created_at` outlives the key it used to be the head of, because
/// `list_logs` still orders by it.
///
/// `detail` is a bounded `varchar` rather than `text` because MySQL cannot index
/// a `TEXT` column in a key without a prefix length. That reason lapsed with the
/// composite key, but the bound is kept: details are structurally bounded format
/// strings — UUIDs (36) plus names the admin form caps at 40–50 chars — and the
/// longest row in the production database is 192 characters. Widening it later is
/// a compatible change; narrowing is not. SQLite ignores `varchar` lengths
/// entirely, so existing rows are unaffected either way.
#[derive(Clone, Debug, PartialEq, Eq, DeriveEntityModel)]
#[sea_orm(table_name = "event_log")]
pub struct Model {
    #[sea_orm(primary_key)]
    pub id: i64,
    #[sea_orm(indexed)]
    pub created_at: i64,
    pub connection_id: Uuid,
    #[sea_orm(column_type = "String(StringLen::N(512))")]
    pub detail: String,
    pub log_type: String,
    pub user_id: Uuid,
}

#[derive(Copy, Clone, Debug, EnumIter, DeriveRelation)]
pub enum Relation {}

impl ActiveModelBehavior for ActiveModel {}
